export function getAvailableTools(): ToolDefinition[] {
  return TOOL_REGISTRY.filter((tool) => tool.status === 'available');
}

export function getToolById(id: string): ToolDefinition | undefined {
  return TOOL_REGISTRY.find((tool) => tool.id === (id as ToolId));
}

export function getAvailableToolById(id: string): ToolDefinition | undefined {
  return TOOL_REGISTRY.find(
    (tool) => tool.id === (id as ToolId) && tool.status === 'available'
  );
}

export function getToolsByCategory(
  categoryId: ToolCategoryId,
  onlyAvailable = true
): ToolDefinition[] {
  return TOOL_REGISTRY.filter(
    (tool) =>
      tool.category === categoryId && (!onlyAvailable || tool.status === 'available')
  );
}
